use std::fs;
use std::path::Path;

fn ensure_icons() {
    let icons_dir = Path::new("icons");
    let _ = fs::create_dir_all(icons_dir);

    let ico_path = icons_dir.join("icon.ico");
    if !ico_path.exists() {
        let _ = fs::write(&ico_path, ICO_BYTES);
    }

    let png_targets = [
        "32x32.png",
        "128x128.png",
        "128x128@2x.png",
        "icon16.png",
        "icon32.png",
        "icon48.png",
        "icon128.png",
    ];

    for name in png_targets {
        let p = icons_dir.join(name);
        if !p.exists() {
            let _ = fs::write(&p, PNG_BYTES);
        }
    }

    let icns_path = icons_dir.join("icon.icns");
    if !icns_path.exists() {
        let _ = fs::write(&icns_path, PNG_BYTES);
    }
}

